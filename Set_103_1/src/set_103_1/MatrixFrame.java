    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String rowstring=jTextField1.getText();
        String columnstring=jTextField2.getText();
        if(rowstring.isEmpty())
            JOptionPane.showMessageDialog(null,"Row can not be empty.");
        else if(columnstring.isEmpty())
            JOptionPane.showMessageDialog(null,"Column can not be empty.");
        else
        {
            row=Integer.parseInt(rowstring);
            column=Integer.parseInt(columnstring);
            mat=new int[row][column];
            JOptionPane.showMessageDialog(null,"Matrix formed successfully.");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        String elestring=jTextField3.getText();
        if(elestring.isEmpty())
            JOptionPane.showMessageDialog(null,"Please, Enter the element of matrix.");
        else
        {
            System.out.println("i = "+i);
            System.out.println("j = "+j);
            int element=Integer.parseInt(elestring);
            if(i<row)
            {
                if(j<column)
                {
                    mat[i][j]=element;
                    System.out.println("mat[" + i +"]" + j +"]="+mat[i][j]);
                    j++;
                    matstr=matstr+elestring+" ";
                    if(j==column)
                    {
                        j=0;
                        i=i+1;
                        matstr=matstr+"\n";
                    }
                }
                jTextField3.setText("");
                jTextArea1.setText(matstr);
                System.out.println("\n----------------------\n");
            }
            else
               JOptionPane.showMessageDialog(null,"Matrix is full."); 
        }
    }//GEN-LAST:event_jButton2ActionPerformed

